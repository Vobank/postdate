/** A translator for `lang`; anything missing falls back to English. */
export function messages(lang) {
  const own = MESSAGES[lang] ?? {};
  return (key, vars = {}) =>
    (own[key] ?? MESSAGES.en[key] ?? key).replace(/\{(\w+)\}/g, (whole, name) =>
      name in vars ? String(vars[name]) : whole,
    );
}
